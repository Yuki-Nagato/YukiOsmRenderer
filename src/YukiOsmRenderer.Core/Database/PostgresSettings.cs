using System.Globalization;
using System.Text;

namespace YukiOsmRenderer.Core.Database {
    /// <summary>Server settings of the bundled PostgreSQL instance.</summary>
    public sealed record PostgresSettings {
        public int MaxConnections { get; init; } = 100;

        public long SharedBuffersMegabytes { get; init; } = 512;

        public long WorkMemMegabytes { get; init; } = 64;

        public long MaintenanceWorkMemMegabytes { get; init; } = 1024;

        public long EffectiveCacheSizeMegabytes { get; init; } = 4096;

        public int MaxParallelMaintenanceWorkers { get; init; } = 2;

        /// <summary>Settings sized for this machine and the given number of concurrent render threads.</summary>
        public static PostgresSettings ForMachine(int renderThreads) {
            var totalMegabytes = GC.GetGCMemoryInfo().TotalAvailableMemoryBytes / (1024 * 1024);
            return ForMemory(totalMegabytes, renderThreads, Environment.ProcessorCount, OperatingSystem.IsWindows());
        }

        public static PostgresSettings ForMemory(long totalMegabytes, int renderThreads, int processorCount, bool windows) {
            // PostgreSQL on Windows rejects work_mem and maintenance_work_mem values of 2 GB and more.
            var perOperationLimit = windows ? 2047 : 8192;
            return new PostgresSettings {
                // Every render thread may hold one connection per Mapnik connection pool; leave room for the importer.
                MaxConnections = Math.Max(100, renderThreads * 4 + 20),
                SharedBuffersMegabytes = Math.Clamp(totalMegabytes / 8, 128, 8192),
                WorkMemMegabytes = Math.Clamp(totalMegabytes / 256, 16, 256),
                MaintenanceWorkMemMegabytes = Math.Clamp(totalMegabytes / 16, 256, perOperationLimit),
                EffectiveCacheSizeMegabytes = Math.Max(512, totalMegabytes / 2),
                MaxParallelMaintenanceWorkers = Math.Clamp(processorCount / 2, 1, 8),
            };
        }

        /// <summary>
        /// Content of the configuration file included by postgresql.conf. The data is rebuilt from the input files
        /// whenever an import does not complete, so durability is traded for import speed.
        /// </summary>
        public string ToConfigurationFile(int port) {
            var builder = new StringBuilder();
            builder.Append("# Generated by YukiOsmRenderer; overwritten on every start.\n");
            Append("listen_addresses", "'127.0.0.1'");
            Append("port", port.ToString(CultureInfo.InvariantCulture));
            Append("unix_socket_directories", "''");
            Append("max_connections", MaxConnections.ToString(CultureInfo.InvariantCulture));
            Append("shared_buffers", $"'{SharedBuffersMegabytes}MB'");
            Append("work_mem", $"'{WorkMemMegabytes}MB'");
            Append("maintenance_work_mem", $"'{MaintenanceWorkMemMegabytes}MB'");
            Append("effective_cache_size", $"'{EffectiveCacheSizeMegabytes}MB'");
            Append("max_parallel_maintenance_workers", MaxParallelMaintenanceWorkers.ToString(CultureInfo.InvariantCulture));
            Append("jit", "off");
            Append("fsync", "off");
            Append("synchronous_commit", "off");
            Append("full_page_writes", "off");
            Append("wal_level", "minimal");
            Append("max_wal_senders", "0");
            Append("max_wal_size", "'8GB'");
            Append("checkpoint_timeout", "'30min'");
            Append("random_page_cost", "1.1");
            Append("logging_collector", "off");
            Append("log_min_messages", "warning");
            Append("lc_messages", "'C'");
            return builder.ToString();

            void Append(string name, string value) {
                builder.Append(name).Append(" = ").Append(value).Append('\n');
            }
        }
    }
}
